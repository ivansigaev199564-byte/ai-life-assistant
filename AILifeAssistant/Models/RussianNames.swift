/// Словарь распространённых имён.
///
/// Сравнение по основе не отличает «Даню» от «Даны»: они расходятся
/// той же гласной, что «Миша» и «Мише». Без словаря выбор был между
/// склейкой разных людей и расщеплением одного, и оба варианта плохи.
///
/// Словарь решает частый случай и честно молчит в остальных: если хотя бы
/// одно написание ему незнакомо, решает сравнение по основе, где разбор
/// остаётся в пользу объединения падежей.
enum RussianNames {

    /// Кому может принадлежать форма.
    ///
    /// Множество, а не одно имя: «Дане» это и Дана, и Даня, и притворяться,
    /// что язык здесь однозначен, значит вернуться к той же ошибке с другой
    /// стороны. Формы перечислены явно, потому что правило и было
    /// источником проблемы.
    static let owners: [String: Set<String>] = {
        var table: [String: Set<String>] = [:]

        for (canonical, variants) in declensions {
            // Ключи проходят ту же нормализацию, что и имена при поиске:
            // иначе «Серёжа» из словаря никогда не совпадёт с «Сережей»
            // из речи, потому что поиск снимает диакритику.
            let key = Person.normalize(canonical)
            table[key, default: []].insert(key)

            for variant in variants {
                table[Person.normalize(variant), default: []].insert(key)
            }
        }
        return table
    }()

    /// Кому может принадлежать это написание.
    static func candidates(for name: String) -> Set<String>? {
        owners[Person.normalize(name)]
    }

    /// Один ли это человек по мнению словаря.
    ///
    /// nil означает «словарь не знает»: тогда решает сравнение по основе.
    static func areSamePerson(_ lhs: String, _ rhs: String) -> Bool? {
        guard let left = candidates(for: lhs), let right = candidates(for: rhs) else {
            return nil
        }
        return !left.isDisjoint(with: right)
    }

